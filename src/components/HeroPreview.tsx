import BagDiagram from "@/components/BagDiagram";
import { ZONE_INFO, generateDesign, type Zone } from "@/lib/designEngine";

const ZONE_ORDER: Zone[] = ["main", "front", "side", "inner"];

const design = generateDesign(
  "mediana",
  ["celular", "cartera", "laptop", "botella", "llaves", "cargador"],
  ""
);

export default function HeroPreview() {
  return (
    <div className="rounded-2xl border border-border bg-surface p-6">
      <p className="text-xs font-medium uppercase tracking-wide text-muted">
        Example design · Medium bag
      </p>
      <div className="mt-4">
        <BagDiagram design={design} />
      </div>
      <ul className="mt-5 space-y-3">
        {ZONE_ORDER.filter((zone) => design.zones[zone].length > 0).map((zone) => (
          <li key={zone} className="flex flex-wrap items-center gap-x-3 gap-y-1">
            <span className="text-sm font-medium">{ZONE_INFO[zone].label}</span>
            <span className="flex flex-wrap gap-1.5">
              {design.zones[zone].map((item) => (
                <span
                  key={item}
                  className="rounded-full border border-border bg-background px-2.5 py-0.5 text-xs text-muted"
                >
                  {item}
                </span>
              ))}
            </span>
          </li>
        ))}
      </ul>
      <p className="mt-4 text-xs text-muted">
        Generated by the designer below from six everyday items.
      </p>
    </div>
  );
}
